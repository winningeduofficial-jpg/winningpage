-- =====================================================================
-- banners_seed_unique_idx 제거 — 어드민 배너 등록을 막던 지뢰 (QA 314·315·316).
--
-- 무엇이 문제였나
--   이 인덱스는 배너의 **내용 전체**를 하나로 묶어 유일성을 본다:
--     (title, highlight, subtitle, image_url, button_text, button_link, sort_order)
--   각 컬럼을 coalesce 로 빈 문자열/0 으로 바꿔 넣기 때문에, 값을 비워 두면
--   빈 값끼리도 서로 충돌한다. 그래서 어드민이 배너를 새로 만들 때 위 일곱 개가
--   기존 행과 전부 같으면 23505 로 막힌다 — **하나만 바꾸면 통과**한다.
--
--   운영자에게 이건 "이미 등록된 값입니다(중복)" 한 줄로만 보인다. 제목이 안
--   겹치는데 왜 막히는지 알 수 없고, 겹친 것이 실은 **순서(sort_order)** 인
--   경우가 많다. 2026-08-31 사용자 실측: 배너 등록에서 이 문구가 떴고, 값을
--   하나 바꾸자 바로 저장됐다("갑자기 잘 된다"의 정체).
--
--   QA 314(본문 이미지)·315(모바일 이미지)·316(첨부파일)이 모두 "업로드가 안
--   된다"로 접수됐는데, 실제로는 **업로드는 되고 저장이 막히는** 패턴으로 보인다
--   — 파일을 고르는 순간 스토리지에는 올라가므로(banners/admin/ 에 객체 39개,
--   배너 행은 3개) 신고자 눈에는 업로드 실패로 읽힌다.
--
-- 왜 그냥 지우나
--   이름 그대로 **구 sql/ 시드 스크립트의 중복 삽입 방지용**이었다. 그 체계는
--   2026-08-21 에 폐기·스쿼시됐고, 지금 이 저장소에서 banners 에 쓰는 경로는
--   어드민 폼 하나뿐이다 — on conflict 로 이 인덱스를 쓰는 코드도, banners 에
--   insert 하는 마이그레이션도 없다(실측). 즉 **지키는 대상이 이미 없다.**
--
-- 대체 제약을 두지 않는 이유
--   배너에는 자연스러운 업무 키가 없다. 제목이 같은 배너를 두 개 두는 것도,
--   순서가 같은 배너를 잠시 두는 것도 정상 운영이다(순서 충돌은 QA 337 의
--   자동 재배열이 이미 처리한다 — Admin.tsx saveRow). 없는 규칙을 지어내
--   다시 막는 것보다 열어 두는 편이 맞다.
--
-- ⚠️ 이걸 지운다고 "완전히 같은 배너 두 개"가 막히지 않는다. 그건 운영상
--    실수일 뿐 데이터 무결성 문제가 아니고, 어드민이 목록에서 바로 보고 지울 수
--    있다. 반대로 지금은 **정상 등록이 막히고 그 이유도 안 보인다** — 이쪽이
--    훨씬 나쁘다.
-- =====================================================================

drop index if exists public.banners_seed_unique_idx;


