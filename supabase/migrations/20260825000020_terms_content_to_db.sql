② 회원은 아이디·비밀번호가 유출되어 제3자가 사용하고 있음을 인지한 경우 즉시 회사에 통지하고 회사의 안내에 따라야 합니다. 통지를 게을리하여 발생한 불이익에 대해 회사는 책임지지 않습니다.
③ 회원은 안전한 계정 관리를 위하여 회사가 권고하거나 필요하다고 판단되는 경우 비밀번호를 주기적으로 변경하고, 서비스 접속 종료 시 로그아웃 하여야 합니다.
제11조 (본인인증)
회사는 회원 식별, 보호자-학생 연동, 미성년자 보호, 부정이용 방지, 콜멘토 서비스 상담원 배정 등을 위하여 본인인증을 요구할 수 있습니다.
제12조 (이용 회원의 해지·탈퇴)
① 회원은 언제든지 마이페이지 또는 온라인 고객센터를 통해 탈퇴를 신청할 수 있으며, 회사는 관계법령상 보존의무가 있는 정보를 제외하고 지체 없이 개인정보를 파기합니다.
② 회원이 본 약관 또는 관계법령을 위반하는 경우 회사는 사전 통지 후 이용계약을 해지할 수 있습니다. 다만 긴급한 경우 사후 통지할 수 있습니다.
제13조 (제공 서비스)
회사는 다음의 서비스를 제공합니다. 세부 구성, 명칭 및 제공 방식은 서비스 정책에 따라 변경될 수 있습니다.
·  학습진단 서비스: 학생이 입력한 정보를 통하여 학습 진단리포트 제공
·  목표관리 서비스: 목표·성적·학습 데이터 기반의 학습관리, 리포트 제공
·  수행평가 서비스: 수행평가 주제 추천, 보고서 구성 안내, 결과물 피드백
·  성장설계, 자기평가, 심화탐구 서비스: 안내문·목표·생활·데이터 기반의 학습관리 및 코칭관리
·  온라인 교육서비스: 강의 영상, e-러닝 콘텐츠 등 온라인 학습콘텐츠의 스트리밍·다운로드 제공 및 학습 진도 관리
·  교육콘텐츠 제작 및 제공 서비스: 자체 제작 또는 제휴를 통한 학습자료, 전자문서, 문제은행 등 교육콘텐츠의 제작·판매·제공
·  콜멘토 서비스: 지정 멘토와 화상통화 또는 전화를 통한 학습, 코칭 상담 서비스
·  입시컨설팅 프리미엄 서비스: 입시 정보제공·상담·1:1멘토링 등 부가 서비스
·  특화멘토링 서비스: 지정 멘토와 1:1 학습관리·상담, 멘토링, 코칭 서비스
제14조 (서비스의 제공시간 및 변경)
① 회사는 연중무휴 1일 24시간 온라인 서비스 제공을 원칙으로 하되, 콜멘토서비스 등 상담원이 개입하는 서비스는 별도로 고지하는 운영시간 내에서 제공하며, 시스템 점검·장애·천재지변 등의 사유로 일시 중단할 수 있습니다.
② 회사는 운영상·기술상 상당한 이유가 있는 경우 서비스의 전부 또는 일부를 변경할 수 있으며, 중요한 변경은 사전에 공지합니다.
제15조 (학습진단서비스)
① 회사는 이용자가 정식 회원가입 전 회사가 정한 범위 내에서 서비스의 일부 기능을 무료로 체험할 수 있는 진단서비스를 제공할 수 있습니다.
② 체험서비스의 이용기간, 이용범위, 제공기능은 회사가 정하여 서비스 화면에 안내하며, 회사의 정책에 따라 사전 고지 후 변경되거나 종료될 수 있습니다.
③ 체험서비스 이용을 위해서는 회원가입을 하여야 합니다.  
④ 본 체험서비스는 제32조 따른 디지털 콘텐츠 청약철회 제한의 실효 요건인 '시험 사용 수단'의 제공으로 인정된다.
제16조 (자체 로직 및 AI활용 서비스의 특성 및 한계)
① 회사가 제공하는 서비스의 결과물(주제 추천, 보고서 구성, 피드백, 분석 리포트 등)은 자체 컨설팅 노하우와 기술로직과 AI인공지능을 활용하여 생성한 참고 정보로서, 부정확하거나 오류가 포함될 수 있습니다.
② 회원은 모든 결과물을 참고자료로 활용하여야 하며, 입력자료 기재·제출 및 수행평가 작성의 최종 책임은 회원 본인 및 소속 학교에 있습니다. 회사는 결과물의 활용으로 인한 평가 결과· 학교 성적반영 여부 등에 대해 책임지지 않습니다.
제17조 (입시 정보·합격 예측의 한계 및 면책)
①  입결 데이터·모집요강·전형 정보 등은 각 대학 및 공공기관의 발표 자료를 기반으로 하되, 회사는 그 정확성·최신성을 완전히 보장하지 않으며, 공식적인 사항은 각 대학의 발표를 우선합니다. 회사는 합격·불합격 등 어떠한 입시 결과도 보장하지 않습니다.
② 지원 대학·전형의 선택 및 최종 의사결정은 회원(학생·학부모)의 판단과 책임으로 이루어지며, 회사는 회원의 의사결정 결과에 대해 책임을 지지 않습니다. 
제18조 (회원 자료입력 및 업로드)
① 회원이 업로드 및 직접 기재 내용, 성적 등 자료는 회원 본인의 것이거나 적법하게 제공할 권한이 있는 자료여야 합니다.
② 회원이 타인의 자료를 무단으로 업로드하여 발생한 분쟁·손해에 대한 책임은 회원에게 있으며, 회사는 해당 자료를 분석·리포트 제공 목적 범위 내에서만 처리합니다.
제19조 (데이터의 소유권)
① 회원이 서비스 이용 과정에서 학생이 입력·등록·업로드하는 정보, 성적, 수행평가 안내 자료 등 일체의 데이터에 대한 소유권은 회원 본인에게 있습니다. 회사는 해당 데이터의 소유권을 취득하지 아니하며, 이를 서비스 제공 목적 범위를 초과하여 영리적으로 취득·매매하지 않습니다.
② 회사는 제1항의 데이터를 회원이 신청한 분석·리포트 생성 등 서비스 제공에 필요한 최소한의 범위 내에서만 처리합니다.
③ 회사의 서비스를 통해 생성한 결과물(추천 카드, 리포트, 피드백, 분석 자료 등)에 대한 저작권 및 지식재산권은 회사에게 귀속되며, 회사는 서비스 개선, 통계 작성 등을 위하여 개인을 식별할 수 없는 형태로 이를 활용할 수 있습니다.
④ 학교, 학원 등 기관이 별도 계약을 통해 회사의 서비스를 이용하는 경우, 소속 학생의 데이터에 관한 관리 권한과 책임은 해당 기관에 있으며, 회사는 관계법령에 따라 위탁받은 범위 내에서 데이터를 처리합니다.
제20조 (AI 서비스의 이용 및 이용제한) 
① 회사는 수행평가 서비스 등에 부분적으로 일부 인공지능 기술을 활용하는 서비스를 안정적이고 공정하게 제공하기 위하여 다음 각 항의 공정사용정책(FUP, Fair Use Policy)을 적용합니다.
② 회원은 AI 서비스 이용 시 다음 각 호의 행위를 하여서는 안 되며, 이를 위반하는 경우 회사는 사전 통보 없이 서비스 이용을 제한하거나 계정을 정지·삭제할 수 있고, 이에 대하여 어떠한 환불이나 손해배상도 이루어지지 않습니다.
1. 회사가 지정하지 않은 외부 인공지능 모델을 임의로 연동하거나, 회사가 허가하지 않은 방식으로 서비스를 이용하는 행위
2. 비정상적인 API 확장, 봇(bot) 제작, 매크로·크롤링 등 자동화된 수단으로 질의·요청을 반복하거나 서비스 운영을 방해하는 행위
3. 계정 정보를 제3자와 공유하거나 비정상적으로 많은 사용량을 발생시키는 등 통상적인 학습 목적을 벗어난 방식으로 서비스를 이용하는 행위
4. 질의·입력 과정에서 욕설, 음담패설, 혐오 발언, 차별적 언어 등 공공질서 및 미풍양속에 반하는 내용을 입력하는 행위
5. 학생 본인의 학습 목적 외의 용도로 서비스를 이용하거나 교육에 방해가 되는 콘텐츠 생성을 요청하는 행위
③ 회사는 AI 서비스의 안정적 운영 및 비용 효율화를 위해 회원의 요청 빈도 또는 이용량이 회사가 정한 합리적 기준을 초과하는 경우, 요청 간격 및 횟수를 조정하거나 일시적으로 이용을 제한할 수 있습니다.
④ 회사는 현재 이미지 생성·편집 등 이미지 제작을 지원하는 기능은 제공하지 아니하며, 향후 관련 기능을 추가하는 경우 이를 사전에 공지합니다.
⑤ 본 조에 따른 서비스 제한으로 발생하는 회원의 손해에 대하여 회사는 책임을 지지 않습니다.
제21조 (온라인교육서비스 및 교육콘텐츠의 이용)
① 회원은 회사가 정한 이용기간·이용범위 내에서만 온라인교육서비스 및 교육콘텐츠를 스트리밍 또는 다운로드 방식으로 이용할 수 있으며, 콘텐츠에 대한 이용권한은 회원 본인에게 한정됩니다.
② 회원은 콘텐츠를 녹화, 캡처, 복제, 재배포, 대여, 양도하거나 제3자가 이용하게 하여서는 안 되며, 이를 위반하여 발생한 손해에 대해서는 회원이 책임을 집니다.
③ 콘텐츠의 저작권 및 지식재산권은 회사 또는 정당한 권리자에게 귀속되며, 이용기간 종료 또는 이용계약 해지 시 회원의 콘텐츠 이용권한은 소멸합니다.
④ 회사는 저작권 계약 만료, 콘텐츠 개편 등 합리적인 사유가 있는 경우 사전 공지 후 콘텐츠의 제공을 중단하거나 변경할 수 있습니다.
제22조 (콜멘토 및 특화멘토링 서비스의 이용)
① 콜멘토서비스, 특화멘토링서비스는 회원이 등록한 연락처로 회원이 지정한 멘토 또는 회사가 배정한 멘토가 통화를 진행하는 방식으로 제공되며, 예약 절차 및 이용 방법은 서비스 정책에 따릅니다.
② 회사는 상담 품질관리 및 분쟁 예방 등을 위하여 통화 내용을 영상녹화 할 수 있으며, 이 경우 통화 시작 시 회원에게 녹화 또는 녹취 사실을 사전에 고지하고 별도의 동의를 받습니다. 회원이 녹화에 동의하지 않는 경우 회사는 서비스 제공을 조정하거나 대체 상담 방식을 안내할 수 있습니다.
③ 통화 녹취 파일은 상담 품질관리 및 분쟁 처리 목적 범위 내에서만 이용되며, 개인정보처리방침에서 정한 보유기간 경과 시 지체 없이 파기합니다.
④ 회원의 귀책사유(연락 불가, 예약 시간 미준수 등)로 상담이 정상적으로 이루어지지 못한 경우, 회사는 재상담 제공 의무를 지지 않을 수 있으며 관련 환불 기준은 제33조(환불 규정)에 따릅니다.
⑤ 상담원(멘토)의 답변·조언은 참고용 정보이며, 이를 신뢰하여 회원이 행한 의사결정에 대해 회사는 제17조에 준하여 책임을 지지 않습니다.
제23조 (수행평가 서비스 이용)
① 수행평가 서비스는 이용권 구매 금액에 따라 일정량의 데이터(토큰)가 부여되고, 회원의 실제 서비스 이용 내역에 따라 보유 데이터가 순차적으로 차감되는 방식(이하 "데이터 차감형 이용권")으로 운영됩니다.
② 각 이용권에 안내되는 이용 가능 기간 또는 이용 가능 횟수는 서비스 제공을 보장하는 기간·횟수가 아니며, 실제 이용 가능한 기간과 횟수는 회원별 데이터 사용 유형에 따라 달라질 수 있습니다.
③ 데이터 차감량은 회원의 질의에 대해 회사가 보유한 자체노하우 및 로직 노하우 자료와 AI가 응답을 생성 과정에서 소요되는 연산 처리량에 따라 매 이용 시마다 달라질 수 있으며, 동일한 유형의 이용이라 하더라도 차감되는 데이터량이 상이할 수 있습니다.
④ 회원은 서비스 화면의 상단에 표시되어 있는 도식으로 데이터 잔여량을 확인할 수도 있습니다.
⑤ 이용권은 구매일로부터 2주이내에 사용하여야 하며, 해당 기간 내에 사용하지 않은 데이터는 기간 경과 시 자동으로 소멸된다. 단, 회원은 유효기간 경과 전 제33조에 따라 미사용 데이터 환불을 요청할 수 있으며, 경과 후 처리는 관계법령 및 콘텐츠 이용자보호지침에 따른다.  
⑥ 회사가 제공하는 수행평가 서비스 이용권의 등급별 데이터량과 서비스 이용요금은 회사가 정하여 별도 메뉴로 고지합니다.
⑦ 이용하는 서비스 요금은 서비스 운영 상황에 따라 변경될 수 있으며, 회원에게 불리하게 변경하는 경우에는 사전에 고지 안내합니다.
⑧ 이용권 구매 이후 데이터 소진, 유효기간 경과 등 회원의 귀책사유로 서비스를 이용하지 못하게 된 경우, 회사는 관련 법령 및 제32조, 제33조에서 정한 기준에 따라 처리합니다.
⑨ 본 조에서 정하지 않은 AI 서비스의 공정한 이용 및 이용제한에 관한 사항은 제20조(AI 서비스의 이용 및 이용제한)에 따릅니다.
제24조 (회원의 의무 및 금지행위)
회원은 다음 행위를 하여서는 안 됩니다.
·  타인의 계정·정보를 무단 사용하거나 아이디·콘텐츠를 양도·대여·판매하는 행위
·  서비스·콘텐츠를 무단으로 복제·녹화·캡처·배포·가공하거나 제3자에게 제공하는 행위
·  콜멘토서비스의 상담 내용을 무단으로 녹화,녹음 유포하거나 상담원에게 폭언·성희롱 등 부적절한 언행을 하는 행위
·  멘토 대상인 학생이 아닌 제3자 또는 학부모의 경우는 서비스 불가하며 임의로 중단할 수 있음  
· 콜멘토·특화멘토링 등 1:1 서비스의 직접 이용 대상은 학생회원에 한하며, 학부모회원은 제6조에 따른 자녀 학습현황 열람·관리 권한을 가진다. 제3자·학부모가 학생 계정을 도용하여 이용하는 경우 회사는 제25조 절차에 따라 이용을 제한할 수 있다.
·  동일 계정의 부정 공유, 자동화 프로그램·크롤링 등으로 서비스 운영을 방해하는 행위
·  컴퓨터 바이러스, 악성코드 등 정보통신기기의 정상적인 작동을 방해하는 자료를 게시·전송하는 행위
·  회사, 다른 회원 또는 제3자를 비방하거나 명예를 훼손하는 행위
·  회사의 사전 승낙 없이 서비스를 영리목적으로 이용하거나 광고성 정보를 게시·전송하는 행위
·  허위 정보 기재, 타인의 권리 침해, 법령·공공질서 위반 행위
제25조 (부정이용 금지 및 제재)
① 회사는 동일 계정의 다중 접속·부정 공유, 콘텐츠 무단 복제·녹화 등을 부정이용으로 보고, 수집된 접속기록·IP 등을 토대로 부정이용 여부를 확인할 수 있습니다.
② 회사는 부정이용 적발 시 경고, 서비스 이용 정지, 이용계약 해지 등의 조치를 단계적으로 취할 수 있으며, 회원은 해당 조치를 이유로 이용기간 연장을 요구할 수 없습니다. 다만 회원이 고의·과실 없음을 입증한 경우 정지기간만큼 이용기간을 연장합니다.
③ 회사가 전항에 따라 이용제한 조치를 하는 경우에는 그 사유, 조치의 유형 및 기간, 이의신청 방법을 회원에게 통지합니다.
④ 회사는 계정의 해킹·도용 또는 부정이용에 관하여 정당한 신고가 접수되거나 이에 준하는 사유로 조사가 필요한 경우, 조사가 완료될 때까지 해당 계정의 서비스 이용을 정지할 수 있습니다.
⑤ 이용제한 조치를 받은 회원이 동일한 행위를 2회 이상 반복하거나 30일 이내에 그 사유를 시정하지 아니하는 경우, 회사는 회원자격을 상실시킬 수 있습니다. 이 경우 회사는 회원등록 말소 전 최소 30일의 기간을 정하여 소명 기회를 부여합니다.
제26조 (게시물의 관리 및 권리) 
① 회사는 회원이 등록한 게시물이 본 약관·관계법령에 위배되는 경우 사전 통지 없이 삭제·이동할 수 있습니다.
② 회원의 게시물에 대한 권리는 회원에게 있으나, 회사는 서비스 운영·홍보 목적의 범위 내에서 이를 노출·이용할 수 있으며, 회원은 이에 대해 철회를 요청할 수 있습니다.
③ 회원의 게시물이 타인의 명예를 훼손하거나 저작권 등 권리를 침해하는 내용을 포함하는 경우, 피해를 주장하는 자는 관련 법령이 정한 절차에 따라 해당 게시물의 삭제 또는 게시중단을 요청할 수 있으며, 회사는 관계법령에 따라 필요한 조치를 취합니다.
제27조 (지식재산권) 
① 회사가 제공하는 콘텐츠·소프트웨어·데이터에 대한 저작권 및 지식재산권은 회사 또는 정당한 권리자에게 귀속됩니다. 회원은 회사의 사전 승낙 없이 이를 복제·전송·배포·2차적 저작물 작성 등에 이용할 수 없습니다.
② 회사는 서비스의 특성상 일부 AI 서비스를 통해 생성된 결과물(추천 카드, 리포트, 피드백 등)이 제3자의 저작권 기타 지식재산권을 침해하지 않는다는 점을 보증하지 아니하며, 회원이 해당 결과물을 활용함에 따라 발생하는 책임은 회원에게 있습니다.
③ 회사가 서비스에 사용하는 상표, 로고, 디자인, 서비스명칭 등에 관한 권리는 회사에 귀속되며, 회원은 회사의 사전 서면 동의 없이 이를 수정·복제·배포하거나 상업적으로 이용할 수 없습니다.
제28조 (업무의 위탁 및 개인정보의 처리위탁) 
① 회사는 서비스의 품질 유지, 기능 개선 및 장애 대응 등을 위하여 서비스의 개발·운영, 데이터 처리, 시스템 유지보수 등 업무의 일부를 외부 전문업체(이하 "수탁업체")에 위탁할 수 있습니다.
② 회사가 개인정보의 처리를 수탁업체에 위탁하는 경우, 「개인정보 보호법」에 따라 위탁업무의 내용과 수탁업체를 회원에게 공개하거나 개인정보처리방침을 통해 안내하며, 수탁업체가 개인정보를 안전하게 처리하도록 계약체결 등을 통해 관리·감독합니다.
③ 회사는 관계사(인공지능 모델 제공자 등) 또는 수탁업체와의 계약 종료, 관련 법령이나 정부기관의 명령·제재 등의 사유로 서비스의 전부 또는 일부를 유지할 수 없는 경우, 제14조에 따라 서비스를 변경하거나 중단할 수 있습니다.
제29조 (양도금지) 
회원은 서비스를 이용할 수 있는 권리 및 본 이용계약상의 지위를 타인에게 양도, 증여하거나 이를 담보로 제공할 수 없습니다.
제30조 (유료서비스 및 결제)
① 회원은 회사가 정한 결제수단(신용카드, 계좌이체, 간편결제 등)으로 유료서비스를 결제할 수 있습니다.
② 회사가 제공하는 유료서비스는 이용권 구매, 기간제 상품 등 회원이 결제 시점에 정해진 금액에 대한 서비스를 제공하는 방식이며, 별도의 신청이 없는 한 결제 정보를 보관하여 자동으로 재청구하지 않습니다.
③ 기간제 상품은 회원이 결제한 이용기간이 만료되면 자동으로 갱신되거나 추가 요금이 청구되지 않으며, 계속하여 서비스를 이용하고자 하는 회원은 이용기간 만료 전후에 직접 재결제(재구매) 절차를 진행하여야 합니다.
④ 서비스 이용요금은 회사의 정책에 따라 변경될 수 있으며, 회원에게 불리하게 변경하는 경우에는 적용일로부터 최소 7일 전(중대한 변경은 30일 전)에 사전 고지합니다.
제31조 (미성년자 결제)
① 미성년 회원의 결제는 원칙적으로 법정대리인의 명의 또는 동의 하에 이루어져야 합니다.
② 미성년자가 법정대리인의 동의 없이 결제한 경우, 본인 또는 법정대리인은 관계법령에 따라 해당 계약을 취소할 수 있습니다.
제32조 (청약철회)
① 회원은 콘텐츠·재화를 공급받은 날(또는 이용 가능일)부터 7일 이내에 청약철회를 할 수 있습니다. 단, 청약철회시 환불조건은 제33조 환불규정에 따릅니다.
② 다만 전자상거래 등에서의 소비자보호에 관한 법률 등에 따라, 회원이 이미 이용을 시작하였거나 즉시 제공이 시작되는 온라인 교육서비스·디지털 콘텐츠 등 청약철회가 제한되는 경우, 그리고 상담이 개시된 콜멘토서비스의 경우에는 그러하지 아니한다. 회사는 청약철회가 제한되는 서비스·콘텐츠임을 사전에 표시·고지하고, 제15조에 따른 학습진단서비스 사용시에는  무료로 제공된 학습진단 1회서비스 이므로 제공된 건은 회원의 청약철회권 행사가 적용되지 아니한다. 회사가 이러한 고지·조치를 하지 아니한 경우 회원은 위 제한에도 불구하고 청약철회를 할 수 있다
제33조 (환불 규정)
① 서비스 이용 및 환불은 상품별-서비스별 기준에 따라 차이가 있습니다.
② 기본적인 환불규정은 다음과 같습니다.
·  이용 시작 전: 이미 납부한 금액 전액 반환
·  이용 시작 후 (이용기간 1개월 이내 과정) · 총 이용시간의 1/3 경과 전: 납부 금액의 2/3 반환
·  이용 시작 후 (이용기간 1개월 이내 과정) · 총 이용시간의 1/2 경과 전: 납부 금액의 1/2 반환
·  이용 시작 후 (이용기간 1개월 이내 과정) · 총 이용시간의 1/2 경과 후: 반환하지 않음
·  이용 시작 후 (이용기간 1개월 초과 과정): 반환사유가 발생한 해당 월의 반환금액과 나머지 월의 금액 전액을 합산하여 반환
③ 수행평가서비스, 콜멘토서비스, 학습진단서비스, 성장설계서비스 등의 1회 이용권 서비스 신청자는 해당 서비스(콘텐츠 제공 또는 상담)의 이용이 개시되기 전까지 청약철회가 가능하며, 개시 이후에는 제32조 제2항에 따라 제한된다. 이용권 유효기간은 구매일로부터 2주일(14일) 입니다. 단, 콜멘토서비스는 상담 신청일을 기준으로 한다.
④ 목표관리서비스, 수행평가서비스, 자기평가서비스, 심화탐구서비스는 기간제 이용이 가능하며, 기간제 이용자의 경우에는 기본적인 환불규정에 따릅니다.
⑤ 이용 횟수(회차)를 정하여 구매한 수행평가서비스의 경우, 판매하는 회차제 이용권의 경우 회원이 환불을 요청하면 미사용 잔여 회차에 해당하는 금액을 본조 제2항의 기준에 준하여 환불합니다.
⑥ 온라인으로 제공되는 실시간VOD 등의 콘텐츠제공서비스의 반환금액은 환불 요청일을 기준으로 산정하여 해당금액을 본조 제2항의 기준으로 공제하고 환불합니다.
⑦ 프리미엄 입시컨설팅 등을 포함한 컨설팅 서비스는 회원별 맞춤식 1:1 서비스로 제작-제공되는 프로그램이므로 단순 변심에 대한 환불은 불가능합니다. 단, 회원별 맞춤 제작자료 또는 상담이 개시되기 전에는 제32조 및 본 조 제2항에 따라 환불합니다.
⑧ 1개월 이상의 장기서비스를 신청하여 할인율을 적용 받은 회원이 중도 환불을 요청할 경우 기존에 받은 할인율 적용은 취소됩니다. 환불금액 산정은 이용기간을 월 정액요금 정가(정액) 기준으로 적용하여 재산정하고 나머지 잔액을 환불규정에 의해 환불처리 합니다.
⑨ 회원이 환불을 요청하는 경우 회사는 요청 접수 및 환불규정 확인 후 제32조 청약철회의 경우는 의사표시 받은 날부터 7영업일(1주일) 이내 환불하며, 중도해지 환불은 접수·금액확인 후 10영업일 이내 환불합니다. 다만 금융사 사정 등 회사의 책임 없는 사유로 지연되는 경우에는 예외로 합니다.  
제34조 (과오금의 환급)
결제 과정에서 과오금이 발생한 경우 회사는 결제와 동일한 방법으로 환급하며, 회사의 책임 있는 사유로 발생한 과오금은 전액 환급합니다.
제35조 (회사의 의무)
