-- ---------------------------------------------------------------------
-- (1) 학습 계획 과제
--     CHECK 제약은 create table 안에 인라인으로 둔다(43/52/55번 관례).
-- ---------------------------------------------------------------------
create table if not exists public.goal_plan_tasks (
    id bigint generated by default as identity primary key,
    profile_id uuid not null references public.goal_students(profile_id) on delete cascade,

    -- 과제가 배정된 날짜(실제 달력 날짜). goal_daily_records.record_date와 달리
    -- "가상 날짜"가 아니다 — 학습 계획은 실제 요일·주차 개념이라 실제 달력을 쓴다.
    plan_date date not null,

    -- 과제 내용. AddTaskModal "할 일" 필드(placeholder "예) 미적분 3단원 문제 30개").
    title text not null,

    -- 과목. AddTaskModal 과목 칩 5종의 코드값(한글 라벨은 API 계층에서 왕복 변환).
    subject text not null,

    -- 예상 소요 시간(분). AddTaskModal "예상 소요 시간" 셀렉트(30분~3시간)를
    -- 분 단위로 환산해 저장한다(src/lib/goalPlanUtils.js durationLabelToMinutes).
    duration_minutes integer not null default 0,

    -- 완료 여부. 대시보드 레일의 체크(✓) 액션이 토글한다.
    done boolean not null default false,

    -- 같은 날짜 안에서의 표시 순서. 기본값 0 — 이번 범위는 드래그 재정렬이 없어
    -- 전부 0으로 저장되고 생성 순(id)으로 보이지만, 컬럼을 미리 둬 재정렬 기능이
    -- 추가될 때 마이그레이션 없이 확장 가능하게 한다.
    sort_order integer not null default 0,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint goal_plan_tasks_title_check
        check (char_length(title) between 1 and 100),
    constraint goal_plan_tasks_subject_check
        check (subject in ('korean', 'math', 'english', 'science', 'etc')),
    constraint goal_plan_tasks_duration_minutes_check
        check (duration_minutes >= 0)
);

