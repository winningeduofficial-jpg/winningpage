/**
 * ROUND_HALF_UP (§4 서두 B-01 정본 구현) — **저장소 전체에서 이 한 벌만 존재한다.**
 *
 * `Number.EPSILON` 가산 방식은 HALF_UP 이 아니다. EPSILON(2.22e-16)은 절대값이라 크기 1 이상
 * 피연산자에 더하면 부동소수에 흡수돼 no-op 이 되고, `4.475 * 100 === 447.49999999999994` → 4.47 이
 * 나왔다(rev.1 버그). toPrecision(15) 로 이진 표현 오차를 먼저 걷어낸 뒤 반올림한다.
 * 룩업 인덱스에도 같은 식을 쓴다 — `Math.round` 를 직접 쓰면 `raw = 1.135 → 113.49999999999999`
 * 로 표가 1행 밀린다(§4.1 주석).
 *
 * 이 파일이 의존 그래프의 리프라 여기에 둔다. src/lib/diagnosisScoring.js 가 그대로 재수출하므로
 * 엔진 계약(§6.2)은 바뀌지 않는다 — 사본을 두면 B-01 회귀 수정이 한쪽에만 반영된다.
 *
 * @param {number|null} x
 * @param {number} [d] 소수 자릿수
 * @returns {number|null} x 가 null·NaN 이면 그대로 반환
 */
export function roundHalfUp(x, d = 0) {
  if (x == null || Number.isNaN(x)) return x;
  const sign = x < 0 ? -1 : 1;
  const abs = Math.abs(x);
  const shifted = Number((abs * 10 ** d).toPrecision(15));
  return (sign * Math.round(shifted)) / 10 ** d;
}

export function clamp(v, min, max) {
  return v < min ? min : v > max ? max : v;
}

/** 숫자로 쓸 수 없는 값(null·undefined·NaN·문자열)인지. 예외 대신 null 을 내기 위한 관문. */
export function isUsableNumber(v) {
  return typeof v === 'number' && Number.isFinite(v);
}

