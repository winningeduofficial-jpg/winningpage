-- ---------------------------------------------------------------------
-- (1) 멘토 코멘트
-- ---------------------------------------------------------------------
create table if not exists public.goal_mentor_comments (
    id bigint generated by default as identity primary key,
    profile_id uuid not null references public.goal_students(profile_id) on delete cascade,

    -- 리포트 종류. 학습방향 리포트(#37/#38)는 이번 범위 밖 — 성장 리포트 2종만 다룬다.
    period_type text not null
        check (period_type in ('weekly', 'monthly')),

    -- 기간 키. weekly='그 주 월요일 YMD', monthly='YYYY-MM' — aggregate.js
    -- resolveWeeklyPeriod/resolveMonthlyPeriod 의 periodKey 와 동일 규약(팀장 확정
    -- "순수 달력" 경계, 위 배경 절 참고). 형식 검증은 CHECK 정규식으로 방어한다.
    period_key text not null
        check (
            (period_type = 'weekly' and period_key ~ '^\d{4}-\d{2}-\d{2}$')
            or
            (period_type = 'monthly' and period_key ~ '^\d{4}-\d{2}$')
        ),

    body text not null
        check (char_length(body) between 1 and 2000),

    -- 작성 시각. 리포트 카드의 "YYYY-MM-DD 작성" 표기(dateLabel)가 이 값을 KST로 자른다.
    written_at timestamptz not null default now(),

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    -- 기간당 코멘트는 1건 — 같은 기간에 재작성하면 update(upsert)로 덮어쓴다.
    constraint goal_mentor_comments_period_key unique (profile_id, period_type, period_key)
);

