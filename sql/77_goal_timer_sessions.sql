-- (2) 열린 세션 유일성 — 학생당 진행 중인 세션은 언제나 최대 1개.
--     동시 탭에서 서로 다른 과목을 "시작"해도 DB가 2번째 insert를 23505로
--     거부한다(api/goal/timer.js가 그 오류를 잡아 기존 세션을 마감 후 1회
--     재시도한다).
create unique index if not exists goal_timer_sessions_open_unique
    on public.goal_timer_sessions (profile_id)
    where ended_at is null;

-- 조회: GET(오늘 날짜 과목별 합계)이 이 조합을 쓴다.
create index if not exists goal_timer_sessions_profile_date_idx
    on public.goal_timer_sessions (profile_id, session_date);


-- ---------------------------------------------------------------------
-- (3) RLS — "본인 행 읽기"만 가능(55번:686-696 관례와 동일).
--     클라이언트 write 정책은 두지 않는다 — 쓰기 경로는 service_role을 쓰는
--     api/goal/timer.js 하나뿐이다. 어드민 정책도 select 전용이다
--     (goal_timer_sessions_admin_select) — `for all + with check`는 어드민
--     세션에도 쓰기를 열어 "쓰기는 service_role 전용" 원칙을 어긴다
--     (55번:706-716 goal_students_admin_all과 달리, 이 테이블은 어드민
--     UI에서 직접 수정할 필요가 없어 select만으로 충분하다 — 75번 검수
--     반려 반영).
-- ---------------------------------------------------------------------
alter table public.goal_timer_sessions enable row level security;

drop policy if exists "goal_timer_sessions_select_own" on public.goal_timer_sessions;
create policy "goal_timer_sessions_select_own" on public.goal_timer_sessions
    as permissive for select to authenticated
    using (profile_id = auth.uid());

drop policy if exists "goal_timer_sessions_admin_all" on public.goal_timer_sessions;
drop policy if exists "goal_timer_sessions_admin_select" on public.goal_timer_sessions;
create policy "goal_timer_sessions_admin_select" on public.goal_timer_sessions
    as permissive for select to authenticated
    using (public.is_winning_admin());


-- ---------------------------------------------------------------------
-- (4) updated_at 트리거 — 저장소 공용 함수 재사용(00_base_schema.sql:1432
