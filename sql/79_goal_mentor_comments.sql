-- ---------------------------------------------------------------------
-- (2) RLS — "본인 행 읽기"만 가능. 클라이언트 write 정책은 두지 않는다
--     (쓰기 어드민 UI가 생기기 전까지 쓰기 경로 자체가 없다). 어드민도
--     select 전용이다(`for all` 금지 — sql/75/77 검수 반려 반영, 위 "주의" 절 참고).
-- ---------------------------------------------------------------------
alter table public.goal_mentor_comments enable row level security;

drop policy if exists "goal_mentor_comments_select_own" on public.goal_mentor_comments;
create policy "goal_mentor_comments_select_own" on public.goal_mentor_comments
    as permissive for select to authenticated
    using (profile_id = auth.uid());

drop policy if exists "goal_mentor_comments_admin_all" on public.goal_mentor_comments;
drop policy if exists "goal_mentor_comments_admin_select" on public.goal_mentor_comments;
create policy "goal_mentor_comments_admin_select" on public.goal_mentor_comments
    as permissive for select to authenticated
    using (public.is_winning_admin());


-- ---------------------------------------------------------------------
-- (3) updated_at 트리거 — 저장소 공용 함수 재사용(00_base_schema.sql:1432
--     public.set_updated_at()). 새 함수를 만들지 않는다.
-- ---------------------------------------------------------------------
drop trigger if exists trg_goal_mentor_comments_updated_at on public.goal_mentor_comments;
create trigger trg_goal_mentor_comments_updated_at
    before update on public.goal_mentor_comments
    for each row execute function public.set_updated_at();


