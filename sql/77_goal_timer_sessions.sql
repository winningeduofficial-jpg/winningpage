--  - src/pages/goal/Timer.jsx(:8-11 TODO)는 지금까지 로컬 setInterval mock이었다
--    — 새로고침·탭 이탈에 값이 사라지고, 원본 외부 앱(target)처럼 클라이언트가
--    계산한 초를 그대로 서버가 믿는 구조는 변조 가능하다(브라우저 콘솔에서
--    임의 시간을 조작해 전송할 수 있다). 이 테이블은 "서버 시계가 유일 진실"
--    원칙으로 새로 설계한 신규 기능이다 — target에서 역산할 원본 스키마가
--    없어 컬럼 코멘트에 원본 참조가 없다.
--  - `duration_seconds`는 클라이언트가 보내는 값이 아니라, 세션을 마감하는
--    시점에 서버가 `ended_at - started_at`으로 직접 계산해 채운다
--    (api/goal/timer.js). 진행 중인 세션(`ended_at is null`)은 항상 null이다.
--  - 동시 탭에서 서로 다른 과목을 "시작"해 열린 세션이 2개 이상 생기면 어느
--    쪽이 진짜인지 판정할 수 없다 — partial unique index
--    `(profile_id) where ended_at is null`로 "열린 세션은 학생당 최대 1개"를
--    DB 레벨에서 강제한다. 새 세션을 시작하려면 반드시 기존 열린 세션을
--    먼저 마감(`end_reason='switch'`)해야 하고, 그 마감·insert는
--    api/goal/timer.js가 한 트랜잭션처럼 순서대로 수행한다.
--  - `end_reason`은 세션이 왜 끝났는지 감사 기록이다: 사용자가 직접 멈춤
--    (stop), 다른 과목을 시작해 자동 마감(switch), 자정을 넘겨 서버가
--    분할 마감(midnight — 같은 과목으로 다음날 00:00에 연속 세션을 새로
--    insert한다), 하트비트가 5분 넘게 끊겨 서버가 정리(timeout — 탭을 닫거나
--    기기가 잠들어 stop 요청이 오지 못한 경우의 안전망).
--
-- 의존성:
--   - 00_base_schema.sql : public.is_winning_admin()(1338행),
--                          public.set_updated_at()(1432행)
--   - sql/55_goal_management.sql : public.goal_students(profile_id) FK 대상
