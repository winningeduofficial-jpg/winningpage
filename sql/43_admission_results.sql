-- =====================================================================
-- 입결정보 페이지(/admission/results) 리뉴얼 — 데이터 레이어 스키마.
-- Supabase SQL Editor / Management API에서 수동 실행 필요. (idempotent)
--
-- 배경:
--  기존 입결 데이터는 같은 도메인(대학·모집단위별 입결)이 두 개의
--  서로 다른 포맷·테이블로 나뉘어 있었다.
--   - admission_susi_results : long 포맷. year가 "행"으로 존재해서
--     다개년 비교 쿼리가 `where year in (...)` 한 번으로 끝난다.
--   - admission_jungsi_results : wide 포맷. 연도가 past_accept_2411 /
--     past_70_2411 … past_accept_1911 / past_70_1911 처럼 "컬럼"에
--     박혀 있다. 2025·2026학년도가 추가되려면 컬럼을 계속 늘려야 하고,
--     신규 연도 축이 스키마 자체에 없어 `/admission/results` 리뉴얼
--     v1이 정시를 다루지 못하는 직접적 원인이었다.
--
--  또한 src/pages/Admin.jsx:785의 admissionResults 섹션은 애초에
--  존재하지 않는 테이블 `admission_results`를 가리키고 있었다(dev REST
--  실측 PGRST205). 그 섹션이 정의해 둔 컬럼셋(result_year / department /
--  recruitment_period / screening_category / admission_track /
--  score_label / is_active)이 사실상 "수시·정시를 한 테이블로 합치면
--  이런 모양이어야 한다"는 설계도였으므로, 이번 통합 테이블 이름과
--  컬럼 구성은 그 설계도를 그대로 살려 지었다.
--
--  이 파일은 위 두 레거시 포맷을 정본 long 포맷 단일 테이블
--  public.admission_results로 통합한다. recruitment_period
--  ('수시'|'정시')가 두 도메인을 가르는 축이다. 셀렉터가 원본을
--  select('*')로 그대로 읽으면 대입모집요강에서 겪은 사고(218행 =
--  5MB+ 응답 → statement timeout 57014, sql/39 참고)를 재현하므로
--  "대학명 + 모집단위 수", "학과명 + 전형 태그"만 수십 바이트로 내려주는
--  경량 집계 뷰 2종을 함께 둔다. "지금 뜨고 있는 학과" 큐레이션은
--  경쟁률 상승률 같은 파생 지표에 최소 2개년 실데이터가 필요한데
--  admission_results가 현재 0행이라 산출이 불가능해 별도 운영자 관리
--  테이블(trending_departments)로 둔다.
--
--  레거시 테이블(admission_susi_results / admission_jungsi_results)은
--  로컬·dev·운영(도쿄, ucjlcvqvinspmrasvsug) 세 환경 모두 0행임을
--  확인했다(2026-08-05). 이관 대상 데이터 자체가 존재하지 않으므로
--  이 파일에는 이관 SQL을 두지 않는다. 두 테이블은 완전한 빈 껍데기이며
--  향후 DROP 후보이지만, 운영 DDL 변경은 별도 승인 사안이라 지금은
--  comment on table로 deprecated 표기만 남긴다.
--
-- security_invoker = true : PostgreSQL 17(이 프로젝트 버전)부터 지원.
-- 뷰 실행 권한을 뷰 소유자가 아닌 "호출자" 권한으로 강제해, 기반 테이블
-- admission_results의 RLS 정책을 뷰에서도 동일하게 존중하게 한다.
-- (sql/39_admission_resource_index_view.sql:26 관례)
-- =====================================================================

-- ---------------------------------------------------------------------
-- (1) 통합 테이블
-- ---------------------------------------------------------------------
create table if not exists public.admission_results (
    id bigint generated by default as identity primary key,

    result_year        smallint not null,
    recruitment_period text     not null,   -- '수시' | '정시' (통합 축)

    university_key   text not null,
    university_name  text not null,
    department_key   text not null,
    department_name  text not null,

    main_track         text,   -- 중심전형: 학생부교과|학생부종합|논술|실기|기타
    screening_category text,   -- 전형유형: 일반|추천형|농어촌|기회균형|논술|기타
    admission_track    text not null,  -- 전형명 원문

    grade_50 numeric(4,2),
    grade_70 numeric(4,2),
    grade_85 numeric(4,2),
    grade_90 numeric(4,2),
    converted_score numeric,
    percentile      numeric,

    quota            integer,
    competition_rate numeric(6,2),
    waitlist_rank    text,
    subject_reflection text,

    is_active   boolean not null default true,
    source_sheet text,
    source_row   integer,
    note         text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint admission_results_recruitment_period_check
        check (recruitment_period in ('수시', '정시')),
    constraint admission_results_result_year_check
        check (result_year between 2015 and 2035)
);

comment on table public.admission_results is
    '입결 통합 테이블(long 포맷). admission_susi_results/admission_jungsi_results 두 레거시 테이블을 recruitment_period 축으로 합친 정본. sql/43_admission_results.sql 참고.';

-- 유일성: 표현식 인덱스 (constraint가 아닌 index — coalesce 표현식 포함).
-- 같은 (연도, 모집시기, 대학, 모집단위, 전형, 반영교과) 조합이 중복 적재되면
-- 화면 표는 첫 행만 보여주는데 평균 계산은 두 행을 모두 합산해, 사용자가
-- 눈에 보이는 셀 값으로 평균을 검산하면 안 맞는 오류가 생긴다. QA가 잡은
-- 결함을 DB 레벨에서 원천 차단한다.
create unique index if not exists admission_results_unique_key_idx
    on public.admission_results (
        result_year,
        recruitment_period,
        university_key,
        department_key,
        admission_track,
        (coalesce(subject_reflection, ''))
    );

-- 상세 조회(university_key, department_key, year) 인덱스
create index if not exists admission_results_detail_idx
    on public.admission_results (university_key, department_key, result_year);

-- 셀렉터(recruitment_period, university_key) 인덱스
create index if not exists admission_results_selector_idx
    on public.admission_results (recruitment_period, university_key);

-- ---------------------------------------------------------------------
-- (2) 집계 뷰 2종
-- ---------------------------------------------------------------------

-- 대학 인덱스 — 검색 뷰 진입 시 1회 (Q1)
-- university_name은 같은 university_key 안에서 표기 흔들림이 있을 수 있어
-- min()으로 대표값 하나를 고정한다(응답 순서에 따라 라벨이 바뀌는 것 방지).
create or replace view public.admission_result_university_index
with (security_invoker = true) as
select
    recruitment_period,
    university_key,
    min(university_name)           as university_name,
    count(distinct department_key) as dept_count
from public.admission_results
where university_key is not null
  and is_active = true
group by recruitment_period, university_key;

-- 모집단위 인덱스 — 대학 선택 시 (Q2)
-- tracks = 그 모집단위에 존재하는 main_track distinct 배열. 셀렉터 행의
-- 전형 태그("학생부교과·학생부종합·논술")를 그리는 데 쓴다.
create or replace view public.admission_result_department_index
with (security_invoker = true) as
select
    recruitment_period,
    university_key,
    department_key,
    min(department_name) as department_name,
    array_agg(distinct main_track) filter (where main_track is not null) as tracks
from public.admission_results
where university_key is not null
  and department_key is not null
  and is_active = true
group by recruitment_period, university_key, department_key;

grant select on public.admission_result_university_index to anon, authenticated;
grant select on public.admission_result_department_index to anon, authenticated;

-- ---------------------------------------------------------------------
-- (3) RLS
-- ---------------------------------------------------------------------
alter table public.admission_results enable row level security;

drop policy if exists "Public read admission results" on public.admission_results;
create policy "Public read admission results" on public.admission_results
    as permissive for select to anon, authenticated
    using (is_active = true);

drop policy if exists "Admin manage admission results" on public.admission_results;
create policy "Admin manage admission results" on public.admission_results
    as permissive for all to authenticated
    using (public.is_winning_admin())
    with check (public.is_winning_admin());

-- ---------------------------------------------------------------------
-- (4) updated_at 트리거 — 저장소 공용 함수 재사용 (00_base_schema.sql:1424
--     public.set_updated_at(), admin_* / banners / galleries 등 다수 테이블이
--     이미 쓰는 관례). 새 함수를 만들지 않는다.
-- ---------------------------------------------------------------------
drop trigger if exists trg_admission_results_updated_at on public.admission_results;
create trigger trg_admission_results_updated_at
    before update on public.admission_results
    for each row execute function public.set_updated_at();

