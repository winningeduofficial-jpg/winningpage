-- ---------------------------------------------------------------------
-- (1) 열공 타이머 세션
--     CHECK 제약은 create table 안에 인라인으로 둔다(43/52/55/75번 관례).
-- ---------------------------------------------------------------------
create table if not exists public.goal_timer_sessions (
    id bigint generated by default as identity primary key,
    profile_id uuid not null references public.goal_students(profile_id) on delete cascade,

    -- 측정 과목. SubjectTimerCard 4장 + 기타 1종(과목 목표는 5종 전부 지원).
    subject text not null,

    -- 이 세션이 속한 날짜(KST, started_at 시점 기준). 서버가 kstYMD(startedAt)로
    -- 채운다 — 자정을 넘겨 계속 진행 중인 세션은 reconcile이 이 값과 오늘(KST)의
    -- 불일치를 감지해 분할 마감하는 트리거 조건으로 쓴다(end_reason='midnight').
    session_date date not null,

    -- 세션 시작 시각. 서버 now() — 클라이언트가 보낸 시각은 쓰지 않는다.
    started_at timestamptz not null,

    -- 세션 종료 시각. null이면 진행 중(= "열린 세션"). 마감 시 서버 now()로 채운다.
    ended_at timestamptz,

    -- 마지막 하트비트 수신 시각. 클라이언트가 60초 간격 + pagehide에서 touch한다.
    -- 스테일 스윕(now - coalesce(last_heartbeat_at, started_at) > 5분)이 열린
    -- 세션을 강제 마감(end_reason='timeout')할지 판단하는 기준이다.
    last_heartbeat_at timestamptz,

    -- 세션 길이(초). 진행 중(ended_at is null)이면 항상 null — 서버가 마감
    -- 시점에 ended_at - started_at으로 1회 계산해 채우고 그 뒤로 바꾸지 않는다.
    -- 상한 43200(12시간)은 방어적 캡: reconcile 스테일 스윕이 놓친 극단값이
    -- 하루 누적 통계를 오염시키는 것을 막는다.
    duration_seconds integer
        check (duration_seconds is null or duration_seconds between 0 and 43200),

    -- 세션이 끝난 사유. 진행 중이면 null. api/goal/timer.js가 채운다.
    end_reason text
        check (end_reason is null or end_reason in ('stop', 'switch', 'midnight', 'timeout')),

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint goal_timer_sessions_subject_check
        check (subject in ('korean', 'math', 'english', 'science', 'etc')),
    -- 진행 중/마감 상태 일관성: 열린 세션은 ended_at·duration_seconds·end_reason이
    -- 전부 비어 있어야 하고, 마감된 세션은 셋 다 채워져 있어야 한다.
    constraint goal_timer_sessions_open_state_check
        check (
            (ended_at is null and duration_seconds is null and end_reason is null)
            or
            (ended_at is not null and duration_seconds is not null and end_reason is not null)
        )
);

