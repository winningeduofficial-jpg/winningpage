-- ---------------------------------------------------------------------
-- (2) RLS — "본인 행 읽기"만 가능(55번:686-696 관례와 동일).
--     클라이언트 write 정책은 두지 않는다 — 쓰기 경로는 service_role을 쓰는
--     api/goal/plan-tasks.js 하나뿐이다.
-- ---------------------------------------------------------------------
alter table public.goal_plan_tasks enable row level security;

drop policy if exists "goal_plan_tasks_select_own" on public.goal_plan_tasks;
create policy "goal_plan_tasks_select_own" on public.goal_plan_tasks
    as permissive for select to authenticated
    using (profile_id = auth.uid());

drop policy if exists "goal_plan_tasks_admin_all" on public.goal_plan_tasks;
create policy "goal_plan_tasks_admin_all" on public.goal_plan_tasks
    as permissive for all to authenticated
    using (public.is_winning_admin())
    with check (public.is_winning_admin());


-- ---------------------------------------------------------------------
-- (3) updated_at 트리거 — 저장소 공용 함수 재사용(00_base_schema.sql:1432
--     public.set_updated_at()). 새 함수를 만들지 않는다.
-- ---------------------------------------------------------------------
drop trigger if exists trg_goal_plan_tasks_updated_at on public.goal_plan_tasks;
create trigger trg_goal_plan_tasks_updated_at
    before update on public.goal_plan_tasks
    for each row execute function public.set_updated_at();


