-- ---------------------------------------------------------------------
drop trigger if exists trg_goal_timer_sessions_updated_at on public.goal_timer_sessions;
create trigger trg_goal_timer_sessions_updated_at
    before update on public.goal_timer_sessions
    for each row execute function public.set_updated_at();


